/**
 * @brief  The application entry point.
 * @retval int
 */
int main(void) {

	/* USER CODE BEGIN 1 */

	/* USER CODE END 1 */

	/* MCU Configuration--------------------------------------------------------*/

	/* Reset of all peripherals, Initializes the Flash interface and the Systick. */
	HAL_Init();

	/* USER CODE BEGIN Init */

	/* USER CODE END Init */

	/* Configure the system clock */
	SystemClock_Config();

	/* USER CODE BEGIN SysInit */

	/* USER CODE END SysInit */

	/* Initialize all configured peripherals */
	MX_GPIO_Init();
	MX_TIM4_Init();
	MX_ADC1_Init();
	MX_USART2_UART_Init();
	/* USER CODE BEGIN 2 */
	HAL_TIM_Base_Start_IT(&htim4);   // arranca el tick de 1 ms
	// tiempo de muestreo largo para el potenciometro (61.5 ciclos)
	ADC_ChannelConfTypeDef sConfig = { 0 };
	sConfig.Channel = ADC_CHANNEL_1;
	sConfig.Rank = ADC_REGULAR_RANK_1;
	sConfig.SingleDiff = ADC_SINGLE_ENDED;
	sConfig.SamplingTime = ADC_SAMPLETIME_61CYCLES_5;
	sConfig.OffsetNumber = ADC_OFFSET_NONE;
	sConfig.Offset = 0;
	HAL_ADC_ConfigChannel(&hadc1, &sConfig);

	// calibracion del adc (se hace una vez al arrancar)
	HAL_ADCEx_Calibration_Start(&hadc1, ADC_SINGLE_ENDED);

	uint32_t h_tick = g_ms;
	/* USER CODE END 2 */

	/* Infinite loop */
	/* USER CODE BEGIN WHILE */
	while (1) {
		/* USER CODE END WHILE */

		/* USER CODE BEGIN 3 */
		// Bloque que corre una vez por cada ms
		if ((uint32_t) (g_ms - h_tick) >= 1U) {
			h_tick = h_tick + 1U;

			// led de actividad, cambia cada 500 ms
			ms_actividad++;
			if (ms_actividad >= 500) {
				ms_actividad = 0;
				HAL_GPIO_TogglePin(GPIOA, GPIO_PIN_5);
			}

			boton_actualizar();
			// una muestra cada 100 ms del adc(sigue en RUN y en PAUSA)
			ms_adc++;
			if (ms_adc >= 100) {
				ms_adc = 0;
				leer_adc();
			}
			// una pulsacion valida cambia entre RUN y PAUSA
			if (evento_boton == 1) {
				evento_boton = 0;
				if (modo == MODO_RUN) {
					modo = MODO_PAUSA;
				} else {
					modo = MODO_RUN;
				}
			}
		}
	}
	/* USER CODE END 3 */
}

